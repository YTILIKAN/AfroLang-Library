def _count_datasets(session: Session) -> int:
    return len(session.exec(select(Dataset)).all())


def _dataset_exists(session: Session, source_slug: str, external_id: str) -> bool:
    statement = (
        select(Dataset)
        .join(Source)
        .where(Source.slug == source_slug, Dataset.external_id == external_id)
    )
    return session.exec(statement).first() is not None


