def seed_catalog(session: Session) -> int:
    """Synchronise le jeu de datasets de démonstration (idempotent par source + external_id)."""
    service = IngestionService(session)
    created = 0
    for payload in _samples():
        existed = _dataset_exists(session, payload.source.slug, payload.external_id)
        service.persist_dataset(payload)
        if not existed:
            created += 1
    return created


def seed_catalog_if_empty(session: Session) -> int:
    if _count_datasets(session) > 0:
        return 0
    return seed_catalog(session)
